function normalizeDocumentText(value) {
  return String(value || "").replace(/[\s\u3000]+/g, "").toLowerCase();
}

function documentQueryTerms(value) {
  const text = String(value || "");
  const terms = new Set();
  for (const match of text.matchAll(/[A-Za-z][A-Za-z0-9-]*|\d+(?:\.\d+)?/g)) {
    if (match[0].length >= 2) terms.add(match[0].toLowerCase());
  }
  for (const match of text.matchAll(/[「“]([^」”]{2,})[」”]/g)) {
    for (const term of match[1].match(/[\u4e00-\u9fa5]{2,}|[A-Za-z0-9]+/g) || []) terms.add(term);
  }
  for (const match of text.match(/[\u4e00-\u9fa5]{2,}/g) || []) {
    for (let index = 0; index < match.length - 1; index += 1) terms.add(match.slice(index, index + 2));
  }
  return Array.from(terms).filter(term => !["是否", "要求", "检查", "核对", "响应", "如下", "如下", "中的", "对应", "文件"].includes(term));
}

function scoreDocumentBlock(block, queries, documentFrequency) {
  const blockText = normalizeDocumentText(block.text || block.heading || "");
  let score = 0;
  queries.forEach(query => {
    const normalizedQuery = normalizeDocumentText(query);
    if (normalizedQuery && blockText.includes(normalizedQuery)) score += 120;
    documentQueryTerms(query).forEach(term => {
      const normalizedTerm = normalizeDocumentText(term);
      if (!normalizedTerm || !blockText.includes(normalizedTerm)) return;
      const frequency = documentFrequency.get(normalizedTerm) || 1;
      score += normalizedTerm.length * (1 + 1 / Math.max(frequency, 1));
    });
  });
  if (block.kind === "table") score += 4;
  if (block.kind === "heading") score += 1;
  return score;
}

function findBestDocumentBlock(container, queries) {
  const doc = Array.isArray(container.__docBlocks) ? container.__docBlocks : [];
  const validQueries = queries.map(query => String(query || "").trim()).filter(Boolean);
  if (!doc.length || !validQueries.length) return null;
  const documentFrequency = new Map();
  doc.forEach(block => {
    const blockText = normalizeDocumentText(block.text || block.heading || "");
    new Set(validQueries.flatMap(documentQueryTerms)).forEach(term => {
      const normalizedTerm = normalizeDocumentText(term);
      if (normalizedTerm && blockText.includes(normalizedTerm)) {
        documentFrequency.set(normalizedTerm, (documentFrequency.get(normalizedTerm) || 0) + 1);
      }
    });
  });
  let bestIndex = -1;
  let bestScore = 0;
  doc.forEach((block, index) => {
    const score = scoreDocumentBlock(block, validQueries, documentFrequency);
    if (score > bestScore) {
      bestScore = score;
      bestIndex = index;
    }
  });
  if (bestIndex < 0 || bestScore < 2) return null;
  return container.querySelector('[data-block-index="' + bestIndex + '"]');
}

function clearLocatedTargets(container) {
  if (!container) return;
  container.querySelectorAll(".doc-located, .doc-cell-located, .flash").forEach(element => {
    element.classList.remove("doc-located", "doc-cell-located", "flash");
  });
}

function findLocatedTableCell(target, queries) {
  const cells = target ? target.querySelectorAll(".doc-table th, .doc-table td") : [];
  if (!cells.length) return null;

  const queryTexts = queries.map(query => String(query || "").trim()).filter(Boolean);
  const terms = new Set();
  queryTexts.forEach(query => {
    const normalizedQuery = normalizeDocumentText(query);
    if (normalizedQuery.length >= 4) terms.add(normalizedQuery);
    documentQueryTerms(query).forEach(term => terms.add(normalizeDocumentText(term)));
  });
  if (!terms.size) return null;

  let bestCell = null;
  let bestScore = 0;
  cells.forEach(cell => {
    const text = normalizeDocumentText(cell.textContent);
    let score = 0;
    terms.forEach(term => {
      if (term && text.includes(term)) score += term.length;
    });
    if (score > bestScore) {
      bestScore = score;
      bestCell = cell;
    }
  });
  return bestScore >= 2 ? bestCell : null;
}

function markLocatedTarget(container, target, queries = []) {
  if (!container || !target) return null;
  clearLocatedTargets(container);
  target.classList.add("doc-located", "flash");
  window.setTimeout(() => target.classList.remove("flash"), 1800);

  const tableCell = findLocatedTableCell(target, queries);
  if (tableCell) {
    tableCell.classList.add("doc-cell-located", "flash");
    window.setTimeout(() => tableCell.classList.remove("flash"), 1800);
  }
  return tableCell || target;
}

