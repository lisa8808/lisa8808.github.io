function highlightTextInElement(element, query) {
  const keyword = String(query || "").trim();
  if (!keyword) return;
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode);
  textNodes.forEach(node => {
    const value = node.nodeValue;
    if (!value.includes(keyword)) return;
    const fragment = document.createDocumentFragment();
    let cursor = 0;
    let index = value.indexOf(keyword);
    while (index !== -1) {
      fragment.appendChild(document.createTextNode(value.slice(cursor, index)));
      const mark = document.createElement("mark");
      mark.dataset.locTarget = "true";
      mark.textContent = value.slice(index, index + keyword.length);
      fragment.appendChild(mark);
      cursor = index + keyword.length;
      index = value.indexOf(keyword, cursor);
    }
    fragment.appendChild(document.createTextNode(value.slice(cursor)));
    node.replaceWith(fragment);
  });
}

function renderDocumentStream(container, doc, query = "") {
  if (!container) return;
  container.innerHTML = "";
  const documentData = Array.isArray(doc) ? doc : [];
  container.__docBlocks = documentData;
  const paper = createRcElement("div", "doc-paper");
  documentData.forEach((block, index) => {
    const element = createRcDocBlock(block);
    element.dataset.blockIndex = String(index);
    element.classList.add("doc-stream-block");
    paper.appendChild(element);
  });
  container.appendChild(paper);
  highlightTextInElement(container, query);
}

function locateTenderText(loc) {
  if (!chapterListEl) return;
  const keyword = loc
    ? String(loc.keyword || loc.highlight || (loc.path && loc.path[loc.path.length - 1]) || "").trim()
    : "";
  renderDocumentStream(chapterListEl, rcTenderDoc, keyword);
  const target = (loc.blockIndex !== undefined && chapterListEl.querySelector('[data-block-index="' + loc.blockIndex + '"]'))
    || chapterListEl.querySelector("mark[data-loc-target]")
    || findBestDocumentBlock(chapterListEl, [loc.keyword, loc.highlight, loc.tender, loc.rule, loc.req, loc.text]);
  if (!target) return;
  const locatedTarget = markLocatedTarget(chapterListEl, target, [loc.keyword, loc.highlight, loc.tender, loc.rule, loc.req, loc.text]);
  locatedTarget.scrollIntoView({ block: "center", inline: "center", behavior: "smooth" });
}

