function uniqueResultTitle(base) {
  const takenTitles = new Set(completedResults.map(item => item.title));
  if (activeTask) takenTitles.add(activeTask.title);
  if (!takenTitles.has(base)) return base;
  let version = 1;
  while (takenTitles.has(base + "_版本" + version)) version += 1;
  return base + "_版本" + version;
}

