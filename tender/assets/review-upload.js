function syncProjectResultTimeline() {
  const projectTime = window.ProjectCreatedTime;
  if (!projectTime || completedResults.length === 0) return;

  const projectName = currentProjectName || projectResultName();
  completedResults = completedResults.map((item, index) => {
    const knownStep = projectTime.stepForTitle(item.title, "review");
    const step = knownStep == null ? index + 1 : knownStep;
    item.projectTimelineStep = step;
    item.projectDisplayOrder = item.kind === "qa" || String(item.title).includes("问答记录") ? -1 : step;
    item.detail = projectTime.resultText(projectName, step);
    return item;
  }).sort((left, right) => right.projectDisplayOrder - left.projectDisplayOrder);
}

