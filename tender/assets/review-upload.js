function addFiles(kind, fileList) {
  const items = Array.from(fileList || []);
  if (items.length === 0) return;
  const maxFileSize = 200 * 1024 * 1024;
  if (kind === "tender") {
    const item = items[0];
    if (!isAllowedFile(item.name)) {
      showToast("仅支持 PDF、DOCX、DOC 格式");
      return;
    }
    if (item.size > maxFileSize) {
      showToast("招标文件大小不能超过 200M");
      return;
    }
    if (tenderFiles.some(file => file.name === item.name)) {
      showToast("已存在同名招标文件「" + item.name + "」，请重新上传相关文件");
      return;
    }
    const replacing = tenderFiles.length > 0;
    tenderFiles.length = 0;
    tenderFiles.push({ name: item.name, size: item.size, selected: true });
    currentProjectName = window.REVIEW_NEW_SESSION && window.realProject ? window.realProject.name : extractProjectName(item.name);
    resetReport();
    renderFiles("tender");
    updateState();
    if (replacing) showToast("已替换为最新上传的招标文件");
    if (reviewProjectId) saveProjectState();
    return;
  }
  const incomingNames = new Set();
  let validItems = items.filter(item => {
    if (!isAllowedFile(item.name) || incomingNames.has(item.name)) return false;
    incomingNames.add(item.name);
    return true;
  });
  if (validItems.length !== items.length) showToast("仅支持 PDF、DOCX、DOC 格式");
  const oversizedFiles = validItems.filter(item => item.size > maxFileSize);
  if (oversizedFiles.length > 0) {
    showToast("投标文件大小不能超过 200M");
    validItems = validItems.filter(item => item.size <= maxFileSize);
  }
  if (validItems.length === 0) return;
  const existingNames = new Set(bidFiles.map(file => file.name));
  const duplicateNames = validItems.filter(item => existingNames.has(item.name)).map(item => item.name);
  if (duplicateNames.length > 0) {
    showToast("已存在同名投标文件「" + duplicateNames.join("」「") + "」，请重新上传相关文件");
  }
  const additions = validItems
    .filter(item => !existingNames.has(item.name))
    .map(item => ({ name: item.name, size: item.size, selected: false }));
  if (additions.length === 0) return;
  const remainingCount = 20 - bidFiles.length;
  if (remainingCount <= 0) {
    showToast("投标文件最多保留 20 份");
    return;
  }
  if (additions.length > remainingCount) {
    showToast("投标文件最多保留 20 份，本次仅保留前 " + remainingCount + " 份");
    additions.splice(remainingCount);
  }
  bidFiles.forEach(file => { file.selected = false; });
  bidFiles.unshift(...additions);
  additions[additions.length - 1].selected = true;
  if (tenderFiles.length === 0) currentProjectName = window.REVIEW_NEW_SESSION && window.realProject ? window.realProject.name : extractProjectName(item.name);
  resetReport();
  renderFiles("bid");
  updateState();
  if (reviewProjectId) saveProjectState();
}

