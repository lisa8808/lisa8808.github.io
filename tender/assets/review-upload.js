function getQaPairFor(message) {
  const messages = Array.from(elements.chatMessages.children);
  const index = messages.indexOf(message);
  if (index < 0) return { question: "", answer: "" };
  let userIndex = -1;
  for (let pos = index; pos >= 0; pos--) {
    if (messages[pos].classList.contains("user")) { userIndex = pos; break; }
  }
  const question = userIndex >= 0 ? messages[userIndex].textContent.trim() : "";
  const answers = [];
  for (let pos = userIndex + 1; pos <= index; pos++) {
    if (messages[pos].classList.contains("assistant")) {
      const textNode = messages[pos].querySelector(".message-text");
      if (textNode && textNode.textContent.trim()) answers.push(textNode.textContent.trim());
    }
  }
  return { question, answer: answers.join("\n") };
}

function refreshSaveNotes() {
  const messages = Array.from(elements.chatMessages.children);
  messages.forEach(message => {
    const existing = message.querySelector(":scope > .message-actions > .save-note");
    if (existing) existing.remove();
  });
  const groupLast = [];
  let current = null;
  messages.forEach(message => {
    if (message.classList.contains("user")) {
      if (current) groupLast.push(current);
      current = null;
    } else if (message.classList.contains("assistant")) {
      current = message;
    }
  });
  if (current) groupLast.push(current);
  groupLast.forEach(message => attachSaveNote(message));
}

