function startEditCheckItem(row, content, item, container) {
  const editor = document.createElement("div");
  editor.className = "check-item-editor";
  const nameInput = document.createElement("input");
  nameInput.type = "text";
  nameInput.className = "item-edit-input";
  nameInput.value = item.text;
  nameInput.placeholder = "请输入检查点";
  const reqInput = document.createElement("input");
  reqInput.type = "text";
  reqInput.className = "item-edit-input req";
  reqInput.value = item.req || item.text || "";
  reqInput.placeholder = "请输入检查要求（判定标准）";
  editor.append(nameInput, reqInput);
  row.replaceChild(editor, content);
  nameInput.focus();
  nameInput.setSelectionRange(nameInput.value.length, nameInput.value.length);
  let done = false;
  const commit = save => {
    if (done) return;
    done = true;
    if (save && nameInput.value.trim() && reqInput.value.trim()) {
      item.text = nameInput.value.trim();
      item.req = reqInput.value.trim();
      showToast("已修改检查项");
    }
    renderCheckItems(container);
  };
  [nameInput, reqInput].forEach(input => {
    input.addEventListener("keydown", event => {
      if (event.key === "Enter") commit(true);
      if (event.key === "Escape") commit(false);
    });
    input.addEventListener("blur", () => commit(true));
    input.addEventListener("click", event => event.stopPropagation());
  });
}

