function syncReportItemsWithChecklist() {
  const source = reportItems.slice();
  const reportByTitle = new Map(source.map(item => [item.title, item]));
  const usedTitles = new Set();
  const nextItems = [];
  const pushItem = item => {
    if (!item || usedTitles.has(item.title)) return;
    usedTitles.add(item.title);
    nextItems.push(item);
  };

  checkItemGroups.forEach(group => {
    if (group.key === "custom") return;
    group.items.forEach(check => {
      const existing = reportByTitle.get(check.text) || (check.issue ? reportByTitle.get(check.issue) : null);
      if (existing) {
        const item = JSON.parse(JSON.stringify(existing));
        item.title = check.text;
        item.checkPoint = check.text;
        if (check.req) item.requirement = check.req;
        pushItem(item);
        return;
      }
      pushItem({
        category: group.name,
        status: "pass",
        title: check.text,
        checkPoint: check.text,
        requirement: check.req || "招标文件对该检查项有明确要求。",
        tender: check.req || "招标文件对该检查项有明确要求。",
        bid: "投标文件相关内容已逐项核对，符合要求。",
        analysis: "未发现缺失或风险。",
        suggestion: "无需修改。",
        summary: "经对照招标文件相应条款，对投标文件中「" + check.text + "」相关内容进行逐项检索与核对，响应内容完整、表述一致，未发现缺失或风险。"
      });
    });
  });

  customCheckItems.forEach(entry => {
    const normalized = normalizeCustomCheckEntry(entry);
    if (!normalized.text) return;
    const existing = reportByTitle.get(normalized.text);
    if (existing) {
      const item = JSON.parse(JSON.stringify(existing));
      item.title = normalized.text;
      item.checkPoint = normalized.text;
      if (normalized.req) item.requirement = normalized.req;
      item.tender = null;
      (item.findings || []).forEach(finding => {
        finding.tenderQuote = null;
        finding.tenderMark = null;
        finding.tenderSource = false;
        finding.tenderSourceNote = finding.tenderSourceNote || "该检查项来自员工自定义新增，本轮检索仅依据检查清单判断投标文件，不回溯招标文件。";
        if (!finding.bidMark) {
          finding.bidSource = false;
          finding.bidSourceNote = finding.bidSourceNote || "该检查项来自员工自定义新增，系统未在投标文件中建立稳定定位，请人工复核。";
        }
      });
      pushItem(item);
      return;
    }
    pushItem(createCustomReportItem(normalized));
  });

  reportItems.splice(0, reportItems.length, ...nextItems);
}

function ensureReviewProject() {
  if (!window.Review2Store) return null;
  if (isRealProjectPreset()) {
    updateRealDemoStatus();
    return null;
  }
  if (reviewProjectId) {
    saveProjectState();
    return reviewProjectId;
  }
  if (tenderFiles.length === 0 && bidFiles.length === 0) return null;
  const store = window.Review2Store;
  const project = store.create({
    scheme: "review1",
    name: currentProjectName,
    tenderFile: { name: tenderFiles[0] ? tenderFiles[0].name : "", size: 0 }
  });
  reviewProjectId = project.id;
  try {
    const url = new URL(window.location.href);
    url.searchParams.set("project", project.id);
    url.searchParams.delete("mode");
    window.history.replaceState(null, "", url.toString());
  } catch (error) {}
  saveProjectState();
  return reviewProjectId;
}

function saveProjectState() {
  if (isRealProjectPreset()) {
    updateRealDemoStatus();
    return;
  }
  if (!window.Review2Store || !reviewProjectId) return;
  const store = window.Review2Store;
  const project = store.find(reviewProjectId);
  if (!project) return;
  project.scheme = "review1";
  project.name = currentProjectName;
  project.tenderFile = { name: tenderFiles[0] ? tenderFiles[0].name : "", size: 0 };
  project.bidFiles = bidFiles.map(file => ({ name: file.name, selected: !!file.selected }));
  const selectedBid = bidFiles.find(file => file.selected);
  project.bidFile = { name: selectedBid ? selectedBid.name : "", size: 0 };
  project.rules = captureChecklistRules();
  project.projectInfoFields = projectInfoFields.map(field => ({ ...field }));
  project.results = completedResults.map(item => ({
    key: item.key,
    kind: item.kind,
    title: item.title,
    icon: item.icon,
    detail: item.detail,
    sources: item.sources || null,
    unread: !!item.unread,
    qa: item.qa || null
  }));
  project.chat = chatTranscript.slice(-200);
  project.flags = { reportGenerated: !!reportGenerated, outlineReady: !!outlineReady, retrieveReady: !!retrieveReady };
  project.updatedAt = Date.now();
  store.save(project);
}

