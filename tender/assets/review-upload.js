  function startReview2() {
    let target = bridgeProject;
    let persisted = true;
    try {
      if (!target) {
        target = bridgeStore.create({
          name: bridgeStore.stripExt(shownTender) || "未命名审查项目",
          tenderFile: { name: shownTender, size: 0 }
        });
      }
      target.rules = captureRules();
      const entry = bridgeStore.addHistory(target, bridgeBid || "投标文件");
      const generatedResults = generateReview2Results();
      entry.results = generatedResults;
      entry.issues = generatedResults.filter(item => item.status !== "pass").length;
      bridgeStore.save(target);
      persisted = bridgeStore.lastWriteOk !== false;
    } catch (error) {
      persisted = false;
    }
    if (!persisted) showToast("浏览器存储不可用或已满，本次审查记录可能无法保存");
    window.location.href = homeUrl(target.id) + "&started=1";
  }

