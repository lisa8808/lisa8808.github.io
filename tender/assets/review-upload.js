function summaryText() {
  const ignoredCount = reportItems.filter(item => rcIgnored.has(item.title)).length;
  return "符合 " + countStatus("pass") + " 项，缺失 " + countStatus("missing") + " 项，风险 " + countStatus("medium") + " 项，严重 " + countStatus("high") + " 项" + (ignoredCount > 0 ? "，已忽略 " + ignoredCount + " 项" : "");
}

