function runRetrieveTask(options = {}) {
  const announce = options.announce !== false;
  if (reviewStage !== "idle") {
    showToast("当前有任务进行中，请稍后再试");
    return false;
  }
  const tenderSelected = tenderFiles.filter(file => file.selected).length;
  const bidSelected = bidFiles.filter(file => file.selected).length;
  if (tenderSelected === 0 || bidSelected === 0) {
    showToast("请先上传招标文件并选中投标文件");
    return false;
  }
  if (!completedResults.some(item => item.kind === "outline")) {
    openOutlineRequiredModal();
    return false;
  }
  syncReportItemsWithChecklist();
  reviewStage = "processing";
  setActiveToolButton("retrieve");
  updateState();
  ensureReviewProject();
  if (announce) {
    const userText = options.userText === undefined ? precisionTasks.retrieve.userText : options.userText;
    if (userText) appendChatMessage("user", userText);
    const ackText = options.ackText === undefined ? precisionTaskAckText("retrieve") : options.ackText;
    if (ackText) appendChatMessage("assistant", ackText);
  }
  const selectedOutline = options.outlineKey
    ? completedResults.find(item => item.kind === "outline" && item.key === options.outlineKey)
    : null;
  const latestOutline = selectedOutline || completedResults.find(item => item.kind === "outline");
  beginGeneratingTask({
    key: "retrieve-" + Date.now(),
    kind: "retrieve",
    title: taskResultTitle("retrieve"),
    icon: resultCatalog.retrieve.icon,
    sources: currentSources(true),
    duration: 3000,
    stopChatText: "已停止审查投标文件，未生成审查结果文件。",
    onComplete: task => {
      retrieveReady = true;
      reportGenerated = true;
      appendChatMessage("assistant", resolveTaskDoneText(precisionTasks.retrieve.doneText, task.title), { followUps: "risk" });
      showToast("审查投标文件已完成");
      recordReviewHistory();
      saveProjectState();
      if (typeof options.onComplete === "function") options.onComplete(task);
    }
  });
  return true;
}

