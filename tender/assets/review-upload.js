function handleChatQuestion(event) {
  event.preventDefault();
  let question = elements.chatQuestionInput.value.trim();
  let usedCarousel = false;
  if (!question && !elements.chatQuestionInput.disabled) {
    question = currentCarouselQuestion();
    usedCarousel = !!question;
    if (question) elements.chatQuestionInput.value = question;
  }
  if (!question) return;
  if (reviewStage === "pending") cancelReviewConfirm(true);
  appendChatMessage("user", question);
  elements.chatQuestionInput.value = "";
  elements.chatInput.classList.remove("has-content");
  if (usedCarousel) advanceQuestionCarousel();
  renderQuestionCarousel();
  window.setTimeout(() => {
    routeChatIntent(question);
  }, 180);
}

function routeChatIntent(question) {
  const tenderSelected = tenderFiles.length;
  const bidSelected = bidFiles.filter(file => file.selected).length;
  const bothReady = tenderSelected > 0 && bidSelected > 0;
  const needBothFiles = text => {
    appendChatMessage("assistant", text + "需要先上传招标文件并选中投标文件，请先完成上传。", { followUps: "default" });
  };
  const strongQuestion = /怎么|如何|怎样|为什么|是什么|什么是|注意事项|介绍|说明|哪些|要点|吗|[？?]/;
  const strongInstruction = /帮我|请|开始|执行|立即|马上|直接/;
  const commandVerb = /生成|给出|提取|梳理|制作|来一份|出一份|做一份|发起|进行/;
  const isQuestionIntent = strongQuestion.test(question) && !strongInstruction.test(question);
  const replyDirectly = () => {
    const reply = getAssistantReply(question);
    appendChatMessage("assistant", reply.text, { citations: reply.citations, followUps: reply.key });
  };
  if (!isQuestionIntent && /一键/.test(question)) {
    if (!bothReady) {
      needBothFiles("一键检索审查");
      return;
    }
    requestQuickConfirm();
    return;
  }
  if (/检查清单|检查项清单|审查项清单|审查项梳理|梳理审查项|审查项提取|提取审查项/.test(question)) {
    if (isQuestionIntent) {
      replyDirectly();
      return;
    }
    if (!bothReady) {
      appendChatMessage("assistant", "生成检查清单需要同时上传招标文件并选中投标文件（用于提取投标文件关键信息），请先完成上传。", { followUps: "default" });
      return;
    }
    if (strongInstruction.test(question) || commandVerb.test(question)) {
      requestOutlineConfirmCard();
      return;
    }
    requestChecklistClarify();
    return;
  }
  if (!isQuestionIntent && /审查投标文件|对投标文件(进行)?审查|审查.*投标文件|投标文件.*审查/.test(question)) {
    if (!bothReady) {
      needBothFiles("审查投标文件");
      return;
    }
    handleChatRetrieveIntent();
    return;
  }
  if (!isQuestionIntent && /检索审查|审查标书|帮我审查|进行审查|审查当前/.test(question)) {
    if (!bothReady) {
      needBothFiles("检索审查");
      return;
    }
    requestReviewChoice();
    return;
  }
  replyDirectly();
}

