function extractProjectName(fileName) {
  const base = stripFileExt(fileName).trim();
  const cleaned = base
    .replace(/[-_—\s]*招标文件.*$/, "")
    .replace(/[-_—\s]*投标文件.*$/, "")
    .replace(/[-_—\s]*(?:最终版|修订版|定稿|终稿|合稿|合版)(?:[-_—\s]*v?\d+(?:\.\d+)?)?$/i, "")
    .replace(/[（(][^（）()]*[)）]\s*$/, "")
    .trim();
  return cleaned || base;
}

