const escapeHtml = (value) => String(value)
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;');

const renderInline = (value) => escapeHtml(value)
  .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');

function formatSelectedSources(sourceCount, knowledgeCount) {
  if (!sourceCount && !knowledgeCount) return '暂未选择来源材料';
  const parts = [];
  if (sourceCount) parts.push(`${sourceCount} 个来源文件`);
  if (knowledgeCount) parts.push(`${knowledgeCount} 个知识库`);
  return `已选 ${parts.join('、')}`;
}

function appendDisplayFiles(target, incoming) {
  const supportedTypes = new Set(['pdf', 'doc', 'docx']);
  const existingNames = new Set(target.map((file) => file.name.toLowerCase()));
  let added = 0;
  let rejected = 0;

  incoming.forEach((entry) => {
    const name = String(entry?.name || '').trim();
    const type = name.includes('.') ? name.split('.').pop().toLowerCase() : '';
    if (!name || !supportedTypes.has(type)) {
      rejected += 1;
      return;
    }
    if (existingNames.has(name.toLowerCase())) return;
    target.push({ name, type, selected: true });
    existingNames.add(name.toLowerCase());
    added += 1;
  });

  return { added, rejected };
}

function extractOutline(markdown, prefix) {
  let section = 0;
  return String(markdown).split(/\r?\n/).flatMap((line) => {
    const match = line.match(/^(#{2,3})\s+(.+)$/);
    if (!match) return [];
    section += 1;
    return [{ level: match[1].length, label: match[2].trim(), id: `${prefix}-section-${section}` }];
  });
}

function renderMarkdown(markdown, prefix) {
  const lines = String(markdown).split(/\r?\n/);
  let section = 0;
  let html = '';
  let listType = null;

  const closeList = () => {
    if (listType) html += `</${listType}>`;
    listType = null;
  };

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index].trim();
    if (!line) {
      closeList();
      continue;
    }

    if (/^\|.+\|$/.test(line) && /^\|(?:\s*:?-+:?\s*\|)+$/.test((lines[index + 1] || '').trim())) {
      closeList();
      const headers = line.slice(1, -1).split('|').map((cell) => cell.trim());
      index += 2;
      const rows = [];
      while (index < lines.length && /^\|.+\|$/.test(lines[index].trim())) {
        rows.push(lines[index].trim().slice(1, -1).split('|').map((cell) => cell.trim()));
        index += 1;
      }
      index -= 1;
      html += `<table><thead><tr>${headers.map((cell) => `<th>${renderInline(cell)}</th>`).join('')}</tr></thead><tbody>${rows.map((row) => `<tr>${row.map((cell) => `<td>${renderInline(cell)}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
      continue;
    }

    const heading = line.match(/^(#{1,3})\s+(.+)$/);
    if (heading) {
      closeList();
      const level = heading[1].length;
      const id = level > 1 ? ` id="${prefix}-section-${section += 1}"` : '';
      html += `<h${level}${id}>${renderInline(heading[2])}</h${level}>`;
      continue;
    }

    const ordered = line.match(/^\d+\.\s+(.+)$/);
    const unordered = line.match(/^[-*]\s+(.+)$/);
    if (ordered || unordered) {
      const nextType = ordered ? 'ol' : 'ul';
      if (listType !== nextType) {
        closeList();
        listType = nextType;
        html += `<${listType}>`;
      }
      html += `<li>${renderInline((ordered || unordered)[1])}</li>`;
      continue;
    }

    closeList();
    html += `<p>${renderInline(line)}</p>`;
  }

  closeList();
  return html;
}

